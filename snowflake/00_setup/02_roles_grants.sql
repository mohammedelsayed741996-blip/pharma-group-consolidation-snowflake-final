/* =============================================================================
   00_setup / 02  Roles and grants
   FIN_ENGINEER       builds and runs the platform (owns all objects below the database)
   GROUP_CONTROLLER   reads every entity in MARTS and AUDIT
   COUNTRY_CONTROLLER reads MARTS, restricted to mapped entities by a row access policy
   Run as: SECURITYADMIN (+ ACCOUNTADMIN for EXECUTE TASK)
   ============================================================================= */
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS FIN_ENGINEER       COMMENT = 'Builds and operates the Helix consolidation platform';
CREATE ROLE IF NOT EXISTS GROUP_CONTROLLER   COMMENT = 'Group Controlling - all entities';
CREATE ROLE IF NOT EXISTS COUNTRY_CONTROLLER COMMENT = 'Country controllers - entities restricted by row access policy';

-- Role hierarchy: custom roles roll up to SYSADMIN, readers roll up to the engineer
GRANT ROLE FIN_ENGINEER       TO ROLE SYSADMIN;
GRANT ROLE GROUP_CONTROLLER   TO ROLE FIN_ENGINEER;
GRANT ROLE COUNTRY_CONTROLLER TO ROLE FIN_ENGINEER;

-- Let the user running the setup assume all three roles
SET SETUP_USER = CURRENT_USER();
GRANT ROLE FIN_ENGINEER       TO USER IDENTIFIER($SETUP_USER);
GRANT ROLE GROUP_CONTROLLER   TO USER IDENTIFIER($SETUP_USER);
GRANT ROLE COUNTRY_CONTROLLER TO USER IDENTIFIER($SETUP_USER);

-- Engineer: full control inside the database
GRANT USAGE, OPERATE ON WAREHOUSE WH_FIN_XS TO ROLE FIN_ENGINEER;
GRANT ALL ON DATABASE HELIX_FIN TO ROLE FIN_ENGINEER;
GRANT ALL ON ALL SCHEMAS IN DATABASE HELIX_FIN TO ROLE FIN_ENGINEER;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE HELIX_FIN TO ROLE FIN_ENGINEER;

-- Readers
GRANT USAGE ON WAREHOUSE WH_FIN_XS TO ROLE GROUP_CONTROLLER;
GRANT USAGE ON WAREHOUSE WH_FIN_XS TO ROLE COUNTRY_CONTROLLER;
GRANT USAGE ON DATABASE HELIX_FIN TO ROLE GROUP_CONTROLLER;
GRANT USAGE ON DATABASE HELIX_FIN TO ROLE COUNTRY_CONTROLLER;
GRANT USAGE ON SCHEMA HELIX_FIN.MARTS TO ROLE GROUP_CONTROLLER;
GRANT USAGE ON SCHEMA HELIX_FIN.MARTS TO ROLE COUNTRY_CONTROLLER;
GRANT USAGE ON SCHEMA HELIX_FIN.AUDIT TO ROLE GROUP_CONTROLLER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA HELIX_FIN.MARTS TO ROLE GROUP_CONTROLLER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA HELIX_FIN.MARTS TO ROLE GROUP_CONTROLLER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA HELIX_FIN.MARTS TO ROLE COUNTRY_CONTROLLER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA HELIX_FIN.MARTS TO ROLE COUNTRY_CONTROLLER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA HELIX_FIN.AUDIT TO ROLE GROUP_CONTROLLER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA HELIX_FIN.AUDIT TO ROLE GROUP_CONTROLLER;

-- Tasks (stream-triggered consolidation) need the account-level EXECUTE TASK privilege
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE FIN_ENGINEER;
