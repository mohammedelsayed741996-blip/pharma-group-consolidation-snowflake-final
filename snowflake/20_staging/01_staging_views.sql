/* =============================================================================
   20_staging / 01  Typed views over RAW
   * Only the latest load of every file is used (re-delivered files replace earlier ones)
   * Trial-balance rows get a SHA2 row hash; exact duplicates within a file are removed
   * Empty strings are kept for "no partner / no cost centre / no profit centre" so that
     joins and grouping never have to deal with NULL keys
   Mirrors: orchestration/reference_engine.py  staging_tb_typed(), staging_tb(), load_master()
   Run as: FIN_ENGINEER
   ============================================================================= */
USE ROLE FIN_ENGINEER;
USE WAREHOUSE WH_FIN_XS;
USE DATABASE HELIX_FIN;
USE SCHEMA STAGING;

-- -----------------------------------------------------------------------------
-- Trial balance
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW STAGING.V_TB_TYPED
    COMMENT = 'Typed TB rows of the latest load of each file, before de-duplication'
AS
WITH latest AS (
    SELECT
        r.*,
        REGEXP_SUBSTR(r._FILE_NAME, 'tb_[A-Z0-9]+_[0-9]{6}[.]csv') AS FILE_NAME
    FROM RAW.TB_LINES r
    QUALIFY r._LOADED_AT = MAX(r._LOADED_AT) OVER (
        PARTITION BY REGEXP_SUBSTR(r._FILE_NAME, 'tb_[A-Z0-9]+_[0-9]{6}[.]csv'))
)
SELECT
    TRIM(COMPANY_CODE)                                         AS COMPANY_CODE,
    TO_NUMBER(FISCAL_YEAR)                                     AS FISCAL_YEAR,
    TO_NUMBER(FISCAL_PERIOD)                                   AS FISCAL_PERIOD,
    TO_VARCHAR(TO_NUMBER(FISCAL_YEAR) * 100 + TO_NUMBER(FISCAL_PERIOD)) AS PERIOD_ID,
    TRIM(GL_ACCOUNT)                                           AS GL_ACCOUNT,
    COALESCE(TRIM(TRADING_PARTNER), '')                        AS TRADING_PARTNER,
    COALESCE(TRIM(COST_CENTER), '')                            AS COST_CENTER,
    COALESCE(TRIM(PROFIT_CENTER), '')                          AS PROFIT_CENTER,
    TRIM(CURRENCY)                                             AS CURRENCY,
    TO_NUMBER(AMOUNT_LC, 38, 2)                                AS AMOUNT_LC,
    TRIM(SOURCE_SYSTEM)                                        AS SOURCE_SYSTEM,
    TRY_TO_TIMESTAMP_NTZ(EXTRACT_TIMESTAMP)                    AS EXTRACT_TS,
    SHA2(CONCAT_WS('|',
        COALESCE(COMPANY_CODE, ''), COALESCE(FISCAL_YEAR, ''), COALESCE(FISCAL_PERIOD, ''),
        COALESCE(GL_ACCOUNT, ''), COALESCE(TRADING_PARTNER, ''), COALESCE(COST_CENTER, ''),
        COALESCE(PROFIT_CENTER, ''), COALESCE(CURRENCY, ''), COALESCE(AMOUNT_LC, '')), 256) AS ROW_HASH,
    FILE_NAME,
    _FILE_ROW_NUMBER                                           AS FILE_ROW_NUMBER,
    _LOAD_ID                                                   AS LOAD_ID,
    _LOADED_AT                                                 AS LOADED_AT
FROM latest;

CREATE OR REPLACE VIEW STAGING.V_TB_LINES
    COMMENT = 'De-duplicated trial-balance rows (exact duplicates within a file removed)'
AS
SELECT *
FROM STAGING.V_TB_TYPED
QUALIFY ROW_NUMBER() OVER (PARTITION BY FILE_NAME, ROW_HASH ORDER BY FILE_ROW_NUMBER) = 1;

-- -----------------------------------------------------------------------------
-- Master data
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW STAGING.V_ENTITIES AS
SELECT
    TRIM(COMPANY_CODE)                         AS COMPANY_CODE,
    COMPANY_NAME,
    COUNTRY_CODE,
    COUNTRY_NAME,
    CITY,
    REGION,
    LOCAL_CURRENCY,
    ENTITY_TYPE,
    COALESCE(PARENT_COMPANY, '')               AS PARENT_COMPANY,
    TO_NUMBER(OWNERSHIP_PCT, 9, 6)             AS OWNERSHIP_PCT,
    CONSOLIDATION_METHOD,
    TO_DATE(ACQUISITION_DATE)                  AS ACQUISITION_DATE,
    TO_NUMBER(GOODWILL_EUR, 38, 2)             AS GOODWILL_EUR,
    LOCAL_CHART_OF_ACCOUNTS,
    SOURCE_SYSTEM,
    TO_NUMBER(STATUTORY_TAX_RATE, 9, 6)        AS STATUTORY_TAX_RATE,
    TO_BOOLEAN(IS_ACTIVE)                      AS IS_ACTIVE
FROM RAW.ENTITIES;

CREATE OR REPLACE VIEW STAGING.V_CURRENCIES AS
SELECT CURRENCY_CODE, CURRENCY_NAME, TO_NUMBER(DECIMALS) AS DECIMALS,
       TO_BOOLEAN(IS_GROUP_CURRENCY) AS IS_GROUP_CURRENCY
FROM RAW.CURRENCIES;

CREATE OR REPLACE VIEW STAGING.V_BUSINESS_UNITS AS
SELECT BUSINESS_UNIT, BUSINESS_UNIT_NAME, SEGMENT
FROM RAW.BUSINESS_UNITS;

CREATE OR REPLACE VIEW STAGING.V_GROUP_ACCOUNTS AS
SELECT
    GROUP_ACCOUNT,
    ACCOUNT_NAME,
    STATEMENT,
    ACCOUNT_CLASS,
    FS_GROUP,
    FS_LINE,
    TO_NUMBER(PRESENTATION_SIGN)               AS PRESENTATION_SIGN,
    TRANSLATION_METHOD,
    TO_BOOLEAN(EBITDA_FLAG)                    AS EBITDA_FLAG,
    COALESCE(NULLIF(CASHFLOW_LINE, ''), 'OP_OTHER') AS CASHFLOW_LINE,
    TO_BOOLEAN(IS_INTERCOMPANY)                AS IS_INTERCOMPANY,
    IC_PAIR_TYPE,
    IC_SIDE,
    TO_BOOLEAN(PARTNER_REQUIRED)               AS PARTNER_REQUIRED,
    TO_BOOLEAN(CONSOLIDATION_ONLY)             AS CONSOLIDATION_ONLY,
    TO_NUMBER(SORT_ORDER)                      AS SORT_ORDER
FROM RAW.GROUP_ACCOUNTS;

CREATE OR REPLACE VIEW STAGING.V_LOCAL_ACCOUNTS AS
SELECT CHART_OF_ACCOUNTS, TRIM(LOCAL_ACCOUNT) AS LOCAL_ACCOUNT, LOCAL_ACCOUNT_NAME, GROUP_ACCOUNT,
       TO_DATE(VALID_FROM) AS VALID_FROM, TO_DATE(VALID_TO) AS VALID_TO
FROM RAW.LOCAL_ACCOUNTS;

CREATE OR REPLACE VIEW STAGING.V_COST_CENTRES AS
SELECT COST_CENTER, COMPANY_CODE, DEPARTMENT, COST_CENTER_NAME, RESPONSIBLE_PERSON,
       DEFAULT_PROFIT_CENTER, FUNCTION, TO_DATE(VALID_FROM) AS VALID_FROM, TO_DATE(VALID_TO) AS VALID_TO,
       TO_BOOLEAN(IS_CURRENT) AS IS_CURRENT, TO_NUMBER(SCD_VERSION) AS SCD_VERSION
FROM RAW.COST_CENTRES;

CREATE OR REPLACE VIEW STAGING.V_PROFIT_CENTRES AS
SELECT PROFIT_CENTER, COMPANY_CODE, BUSINESS_UNIT, SEGMENT, PROFIT_CENTER_NAME
FROM RAW.PROFIT_CENTRES;

CREATE OR REPLACE VIEW STAGING.V_IC_TRANSFER_PRICING AS
SELECT SELLER_COMPANY, FLOW_TYPE, PRICING_METHOD,
       TO_NUMBER(MARKUP_PCT, 18, 6)                 AS MARKUP_PCT,
       TO_NUMBER(SELLER_MARGIN_ON_SALES_PCT, 18, 6) AS SELLER_MARGIN_ON_SALES_PCT,
       SETTLEMENT_CURRENCY, TO_NUMBER(PAYMENT_TERMS_DAYS) AS PAYMENT_TERMS_DAYS
FROM RAW.IC_TRANSFER_PRICING;

CREATE OR REPLACE VIEW STAGING.V_DQ_RULES AS
SELECT RULE_ID, RULE_NAME, SEVERITY, LAYER, DESCRIPTION
FROM RAW.DQ_RULES;

-- -----------------------------------------------------------------------------
-- FX
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW STAGING.V_FX_RATES AS
SELECT CURRENCY, PERIOD_ID,
       TO_NUMBER(AVG_RATE, 38, 6)     AS AVG_RATE,
       TO_NUMBER(CLOSING_RATE, 38, 6) AS CLOSING_RATE,
       RATE_SOURCE
FROM RAW.FX_RATES;

CREATE OR REPLACE VIEW STAGING.V_FX_BUDGET AS
SELECT CURRENCY, TO_NUMBER(FISCAL_YEAR) AS FISCAL_YEAR, TO_NUMBER(BUDGET_RATE, 38, 6) AS BUDGET_RATE
FROM RAW.FX_BUDGET;

CREATE OR REPLACE VIEW STAGING.V_FX_HISTORICAL AS
SELECT COMPANY_CODE, GROUP_ACCOUNT, CURRENCY, TO_NUMBER(HISTORICAL_RATE, 38, 6) AS HISTORICAL_RATE, RATE_BASIS
FROM RAW.FX_HISTORICAL;

-- -----------------------------------------------------------------------------
-- Intercompany sub-ledger, budget, manifest, management adjustments
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW STAGING.V_IC_TRANSACTIONS AS
SELECT IC_DOCUMENT_ID, FLOW_TYPE, SELLER_COMPANY, BUYER_COMPANY,
       TO_NUMBER(FISCAL_YEAR) AS FISCAL_YEAR, TO_NUMBER(FISCAL_PERIOD) AS FISCAL_PERIOD,
       TO_VARCHAR(TO_NUMBER(FISCAL_YEAR) * 100 + TO_NUMBER(FISCAL_PERIOD)) AS PERIOD_ID,
       TO_DATE(DOCUMENT_DATE) AS DOCUMENT_DATE, SELLER_GROUP_ACCOUNT, BUYER_GROUP_ACCOUNT,
       BUSINESS_UNIT, DOCUMENT_CURRENCY, TO_NUMBER(AMOUNT_DOC, 38, 2) AS AMOUNT_DOC
FROM RAW.IC_TRANSACTIONS;

CREATE OR REPLACE VIEW STAGING.V_BUDGET AS
SELECT VERSION, COMPANY_CODE,
       TO_NUMBER(FISCAL_YEAR) AS FISCAL_YEAR, TO_NUMBER(FISCAL_PERIOD) AS FISCAL_PERIOD,
       TO_VARCHAR(TO_NUMBER(FISCAL_YEAR) * 100 + TO_NUMBER(FISCAL_PERIOD)) AS PERIOD_ID,
       GROUP_ACCOUNT, COALESCE(TRADING_PARTNER, '') AS TRADING_PARTNER,
       COALESCE(COST_CENTER, '') AS COST_CENTER, COALESCE(PROFIT_CENTER, '') AS PROFIT_CENTER,
       CURRENCY, TO_NUMBER(AMOUNT_LC, 38, 2) AS AMOUNT_LC
FROM RAW.BUDGET;

CREATE OR REPLACE VIEW STAGING.V_CONTROL_TOTALS AS
SELECT FILE_NAME, COMPANY_CODE,
       TO_VARCHAR(TO_NUMBER(FISCAL_YEAR) * 100 + TO_NUMBER(FISCAL_PERIOD)) AS PERIOD_ID,
       TO_NUMBER(ROW_COUNT) AS ROW_COUNT,
       TO_NUMBER(SUM_AMOUNT_LC, 38, 2) AS SUM_AMOUNT_LC,
       TO_NUMBER(SUM_ABS_AMOUNT_LC, 38, 2) AS SUM_ABS_AMOUNT_LC,
       DELIVERY_STATUS
FROM RAW.CONTROL_TOTALS;

CREATE OR REPLACE VIEW STAGING.V_MGMT_ADJUSTMENTS AS
SELECT ADJUSTMENT_ID, COMPANY_CODE,
       TO_VARCHAR(TO_NUMBER(FISCAL_YEAR) * 100 + TO_NUMBER(FISCAL_PERIOD)) AS PERIOD_ID,
       GROUP_ACCOUNT, COALESCE(COST_CENTER, '') AS COST_CENTER, COALESCE(PROFIT_CENTER, '') AS PROFIT_CENTER,
       TO_NUMBER(AMOUNT_EUR, 38, 2) AS AMOUNT_EUR, ADJUSTMENT_TYPE, DESCRIPTION
FROM RAW.MGMT_ADJUSTMENTS;
