/* =============================================================================
   40_marts / 01  Logic of every mart table (as INTEGRATION.V_MART_* views)
   The views hold the logic; MARTS.SP_REFRESH() materialises them into MARTS tables
   with INSERT OVERWRITE (which keeps grants and row access policies in place).
   Mirrors: orchestration/reference_engine.py  run_reference() -> fact, cashflow()
   Run as: FIN_ENGINEER
   ============================================================================= */
USE ROLE FIN_ENGINEER;
USE WAREHOUSE WH_FIN_XS;
USE DATABASE HELIX_FIN;
USE SCHEMA INTEGRATION;

-- =============================================================================
-- Dimensions
-- =============================================================================
CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_ENTITY AS
SELECT
    e.COMPANY_CODE, e.COMPANY_NAME, e.COUNTRY_CODE, e.COUNTRY_NAME, e.CITY, e.REGION,
    e.LOCAL_CURRENCY, e.ENTITY_TYPE, e.PARENT_COMPANY, COALESCE(p.COMPANY_NAME, '') AS PARENT_NAME,
    e.OWNERSHIP_PCT, e.CONSOLIDATION_METHOD, e.ACQUISITION_DATE, e.GOODWILL_EUR,
    e.LOCAL_CHART_OF_ACCOUNTS, e.SOURCE_SYSTEM, e.STATUTORY_TAX_RATE,
    e.COMPANY_CODE || ' ' || e.COMPANY_NAME AS ENTITY_LABEL
FROM STAGING.V_ENTITIES e
LEFT JOIN STAGING.V_ENTITIES p
       ON p.COMPANY_CODE = e.PARENT_COMPANY;

-- Role-playing copy of the entity dimension for the trading partner (incl. third parties
-- and invalid partner codes found in the data, so that no fact row loses its dimension)
CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_PARTNER AS
SELECT COMPANY_CODE AS PARTNER_CODE, COMPANY_NAME AS PARTNER_NAME, 'GROUP_COMPANY' AS PARTNER_TYPE, TRUE AS IS_VALID
FROM STAGING.V_ENTITIES
UNION ALL
SELECT '', 'Third parties (no trading partner)', 'THIRD_PARTY', TRUE
UNION ALL
SELECT DISTINCT x.TRADING_PARTNER, 'Unknown partner ' || x.TRADING_PARTNER, 'INVALID', FALSE
FROM (
    SELECT TRADING_PARTNER FROM INTEGRATION.GL_TRANSLATED
    UNION
    SELECT TRADING_PARTNER FROM INTEGRATION.V_BUDGET_TRANSLATED
) x
WHERE x.TRADING_PARTNER <> ''
  AND x.TRADING_PARTNER NOT IN (SELECT COMPANY_CODE FROM STAGING.V_ENTITIES);

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_ACCOUNT AS
SELECT
    a.GROUP_ACCOUNT, a.ACCOUNT_NAME, a.GROUP_ACCOUNT || ' ' || a.ACCOUNT_NAME AS ACCOUNT_LABEL,
    a.STATEMENT, a.ACCOUNT_CLASS, a.FS_GROUP, a.FS_LINE, a.PRESENTATION_SIGN, a.TRANSLATION_METHOD,
    a.EBITDA_FLAG, a.CASHFLOW_LINE, a.IS_INTERCOMPANY, a.IC_PAIR_TYPE, a.IC_SIDE,
    a.CONSOLIDATION_ONLY, a.ACCOUNT_SOURCE, a.SORT_ORDER,
    CASE a.FS_GROUP
        WHEN 'Revenue'                     THEN 10
        WHEN 'Cost of sales'               THEN 20
        WHEN 'Operating expenses'          THEN 30
        WHEN 'Non-recurring items'         THEN 35
        WHEN 'Depreciation & amortisation' THEN 40
        WHEN 'Financial result'            THEN 50
        WHEN 'Income tax'                  THEN 60
        WHEN 'Profit attribution'          THEN 70
        WHEN 'Non-current assets'          THEN 110
        WHEN 'Current assets'              THEN 120
        WHEN 'Equity'                      THEN 210
        WHEN 'Non-current liabilities'     THEN 220
        WHEN 'Current liabilities'         THEN 230
        ELSE 999
    END AS FS_GROUP_ORDER
FROM INTEGRATION.V_ACCOUNTS a;

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_PERIOD AS
SELECT
    PERIOD_ID, PERIOD_SEQ, FISCAL_YEAR, FISCAL_PERIOD, FISCAL_QUARTER, FX_PERIOD, PERIOD_END_DATE,
    IS_OPENING,
    IFF(IS_OPENING, 'Opening ' || FISCAL_YEAR, TO_CHAR(PERIOD_END_DATE, 'MON YYYY')) AS PERIOD_NAME,
    'FY' || FISCAL_YEAR                                                           AS FISCAL_YEAR_LABEL,
    IFF(IS_OPENING, 'Opening', 'Q' || FISCAL_QUARTER || ' ' || FISCAL_YEAR)       AS QUARTER_LABEL,
    DATE_TRUNC('MONTH', PERIOD_END_DATE)                                          AS PERIOD_START_DATE
FROM INTEGRATION.V_PERIOD_SPINE;

-- SCD Type 2 cost centres with a surrogate key; key 0 = no cost centre
CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_COST_CENTER AS
SELECT 0 AS COST_CENTER_SK, '' AS COST_CENTER, '' AS COMPANY_CODE, 'N/A' AS DEPARTMENT,
       'Not assigned' AS COST_CENTER_NAME, '' AS RESPONSIBLE_PERSON, '' AS DEFAULT_PROFIT_CENTER,
       'N/A' AS FUNCTION, '1900-01-01'::DATE AS VALID_FROM, '9999-12-31'::DATE AS VALID_TO,
       TRUE AS IS_CURRENT, 1 AS SCD_VERSION
UNION ALL
SELECT ROW_NUMBER() OVER (ORDER BY COST_CENTER, VALID_FROM), COST_CENTER, COMPANY_CODE, DEPARTMENT,
       COST_CENTER_NAME, RESPONSIBLE_PERSON, DEFAULT_PROFIT_CENTER, FUNCTION, VALID_FROM, VALID_TO,
       IS_CURRENT, SCD_VERSION
FROM STAGING.V_COST_CENTRES;

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_PROFIT_CENTER AS
SELECT PROFIT_CENTER, COMPANY_CODE, BUSINESS_UNIT, SEGMENT, PROFIT_CENTER_NAME
FROM STAGING.V_PROFIT_CENTRES
UNION ALL
SELECT '', '', 'UNASSIGNED', 'Unassigned', 'No profit centre';

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_BUSINESS_UNIT AS
SELECT BUSINESS_UNIT, BUSINESS_UNIT_NAME, SEGMENT FROM STAGING.V_BUSINESS_UNITS
UNION ALL
SELECT 'UNASSIGNED', 'Unassigned (balance sheet & consolidation entries)', 'Unassigned';

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_CURRENCY AS
SELECT CURRENCY_CODE, CURRENCY_NAME, DECIMALS, IS_GROUP_CURRENCY FROM STAGING.V_CURRENCIES;

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_LAYER AS
SELECT LAYER, LAYER_ORDER, LAYER_NAME, IN_STATUTORY, IN_MANAGEMENT FROM INTEGRATION.LAYERS;

CREATE OR REPLACE VIEW INTEGRATION.V_MART_DIM_SCENARIO AS
SELECT 'ACT' AS SCENARIO, 'Actual' AS SCENARIO_NAME, 1 AS SCENARIO_ORDER
UNION ALL
SELECT 'BUD', 'Budget', 2;

