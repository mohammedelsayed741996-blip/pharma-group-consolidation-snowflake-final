CREATE OR REPLACE VIEW INTEGRATION.V_MART_FCT_CONSOLIDATED_GL AS
WITH f AS (
    SELECT SCENARIO, LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, TRADING_PARTNER, COST_CENTER,
           PROFIT_CENTER, AMOUNT_LC, AMOUNT_GC, AMOUNT_GC_CC, SOURCE_RULE
    FROM INTEGRATION.GL_TRANSLATED
    UNION ALL
    SELECT SCENARIO, LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, TRADING_PARTNER, COST_CENTER,
           PROFIT_CENTER, AMOUNT_LC, AMOUNT_GC, AMOUNT_GC_CC, SOURCE_RULE
    FROM INTEGRATION.V_BUDGET_TRANSLATED
    UNION ALL
    SELECT SCENARIO, LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, TRADING_PARTNER, COST_CENTER,
           PROFIT_CENTER, AMOUNT_LC, AMOUNT_GC, AMOUNT_GC_CC, SOURCE_RULE
    FROM INTEGRATION.V_IC_ELIM
    UNION ALL
    SELECT SCENARIO, LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, TRADING_PARTNER, COST_CENTER,
           PROFIT_CENTER, AMOUNT_LC, AMOUNT_GC, AMOUNT_GC_CC, SOURCE_RULE
    FROM INTEGRATION.V_CONSOL_ADJ
    UNION ALL
    SELECT SCENARIO, LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, TRADING_PARTNER, COST_CENTER,
           PROFIT_CENTER, AMOUNT_LC, AMOUNT_GC, AMOUNT_GC_CC, SOURCE_RULE
    FROM INTEGRATION.V_MGMT_ADJ
)
SELECT
    f.SCENARIO, f.LAYER, f.PERIOD_ID, f.COMPANY_CODE, f.GROUP_ACCOUNT, f.TRADING_PARTNER,
    COALESCE(cc.COST_CENTER_SK, 0) AS COST_CENTER_SK,
    f.COST_CENTER, f.PROFIT_CENTER, f.SOURCE_RULE, e.LOCAL_CURRENCY,
    f.AMOUNT_LC, f.AMOUNT_GC, f.AMOUNT_GC_CC
FROM f
JOIN INTEGRATION.V_PERIOD_SPINE p
  ON p.PERIOD_ID = f.PERIOD_ID
LEFT JOIN STAGING.V_ENTITIES e
       ON e.COMPANY_CODE = f.COMPANY_CODE
LEFT JOIN INTEGRATION.V_MART_DIM_COST_CENTER cc
       ON cc.COST_CENTER = f.COST_CENTER
      AND cc.COST_CENTER <> ''
      AND p.PERIOD_END_DATE BETWEEN cc.VALID_FROM AND cc.VALID_TO;

-- Indirect cash flow (inflow = positive). TRANSLATED layer: local-currency movements at the
-- average rate plus a separate FX effect on cash. Consolidation layers carry no cash, so
-- their lines net to zero; pure equity reclassifications (NCI_*, CTA) are excluded.
CREATE OR REPLACE VIEW INTEGRATION.V_MART_FCT_CASHFLOW AS
WITH t AS (
    SELECT g.COMPANY_CODE, g.PERIOD_ID, g.GROUP_ACCOUNT, g.AMOUNT_LC, g.AMOUNT_GC,
           a.STATEMENT, a.CASHFLOW_LINE, fx.AVG_RATE
    FROM INTEGRATION.GL_TRANSLATED g
    JOIN INTEGRATION.V_ACCOUNTS a ON a.GROUP_ACCOUNT = g.GROUP_ACCOUNT
    JOIN INTEGRATION.V_PERIOD_SPINE p ON p.PERIOD_ID = g.PERIOD_ID
    LEFT JOIN INTEGRATION.FX_RATES_FILLED fx ON fx.CURRENCY = g.CURRENCY AND fx.FX_PERIOD = p.FX_PERIOD
    WHERE p.PERIOD_SEQ > 0
),
translated_lines AS (
    SELECT 'TRANSLATED' AS LAYER, COMPANY_CODE, PERIOD_ID, 'NET_INCOME' AS CASHFLOW_LINE,
           -SUM(AMOUNT_GC) AS AMOUNT_GC
    FROM t WHERE STATEMENT = 'PL'
    GROUP BY COMPANY_CODE, PERIOD_ID
    UNION ALL
    SELECT 'TRANSLATED', COMPANY_CODE, PERIOD_ID, CASHFLOW_LINE,
           -ROUND(SUM(AMOUNT_LC) / MAX(AVG_RATE), 2)
    FROM t WHERE STATEMENT = 'BS' AND CASHFLOW_LINE <> 'CASH' AND GROUP_ACCOUNT <> '3900'
    GROUP BY COMPANY_CODE, PERIOD_ID, CASHFLOW_LINE
    UNION ALL
    SELECT 'TRANSLATED', COMPANY_CODE, PERIOD_ID, 'FX_EFFECT_ON_CASH',
           SUM(AMOUNT_GC) - ROUND(SUM(AMOUNT_LC) / MAX(AVG_RATE), 2)
    FROM t WHERE CASHFLOW_LINE = 'CASH'
    GROUP BY COMPANY_CODE, PERIOD_ID
),
consolidation_lines AS (
    SELECT x.LAYER, x.COMPANY_CODE, x.PERIOD_ID,
           IFF(a.STATEMENT = 'PL', 'NET_INCOME', a.CASHFLOW_LINE) AS CASHFLOW_LINE,
           -SUM(x.AMOUNT_GC) AS AMOUNT_GC
    FROM (
        SELECT LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, AMOUNT_GC, SOURCE_RULE FROM INTEGRATION.V_IC_ELIM WHERE SCENARIO = 'ACT'
        UNION ALL
        SELECT LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, AMOUNT_GC, SOURCE_RULE FROM INTEGRATION.V_CONSOL_ADJ
        UNION ALL
        SELECT LAYER, COMPANY_CODE, PERIOD_ID, GROUP_ACCOUNT, AMOUNT_GC, SOURCE_RULE FROM INTEGRATION.V_MGMT_ADJ
    ) x
    JOIN INTEGRATION.V_ACCOUNTS a ON a.GROUP_ACCOUNT = x.GROUP_ACCOUNT
    JOIN INTEGRATION.V_PERIOD_SPINE p ON p.PERIOD_ID = x.PERIOD_ID
    WHERE p.PERIOD_SEQ > 0
      AND NOT STARTSWITH(x.SOURCE_RULE, 'NCI_')
      AND x.GROUP_ACCOUNT <> '3900'
    GROUP BY x.LAYER, x.COMPANY_CODE, x.PERIOD_ID, IFF(a.STATEMENT = 'PL', 'NET_INCOME', a.CASHFLOW_LINE)
)
SELECT 'ACT' AS SCENARIO, LAYER, COMPANY_CODE, PERIOD_ID, CASHFLOW_LINE,
       CASE
           WHEN CASHFLOW_LINE = 'NET_INCOME' OR STARTSWITH(CASHFLOW_LINE, 'OP_') THEN 'Operating'
           WHEN STARTSWITH(CASHFLOW_LINE, 'INV_') THEN 'Investing'
           WHEN STARTSWITH(CASHFLOW_LINE, 'FIN_') THEN 'Financing'
           ELSE 'FX effect'
       END AS CASHFLOW_SECTION,
       AMOUNT_GC::NUMBER(38, 2) AS AMOUNT_GC
FROM (
    SELECT * FROM translated_lines
    UNION ALL
    SELECT * FROM consolidation_lines
)
WHERE AMOUNT_GC <> 0;

CREATE OR REPLACE VIEW INTEGRATION.V_MART_FCT_IC_RECON AS
SELECT SCENARIO, PERIOD_ID, PAIR_TYPE, ENTITY_A, ENTITY_B, SIDE_A_GC, SIDE_B_GC, DIFFERENCE_GC,
       TOLERANCE_GC, MATCH_STATUS
FROM INTEGRATION.IC_RECON;

CREATE OR REPLACE VIEW INTEGRATION.V_MART_FCT_FX_RATE AS
SELECT f.CURRENCY, f.FX_PERIOD, f.AVG_RATE, f.CLOSING_RATE, f.RATE_STATUS, b.BUDGET_RATE
FROM INTEGRATION.FX_RATES_FILLED f
LEFT JOIN STAGING.V_FX_BUDGET b
       ON b.CURRENCY = f.CURRENCY
      AND b.FISCAL_YEAR = TO_NUMBER(LEFT(f.FX_PERIOD, 4));

CREATE OR REPLACE VIEW INTEGRATION.V_MART_FCT_IC_DOCUMENTS AS
SELECT IC_DOCUMENT_ID, FLOW_TYPE, SELLER_COMPANY, BUYER_COMPANY, PERIOD_ID, DOCUMENT_DATE,
       SELLER_GROUP_ACCOUNT, BUYER_GROUP_ACCOUNT, BUSINESS_UNIT, DOCUMENT_CURRENCY, AMOUNT_DOC
FROM STAGING.V_IC_TRANSACTIONS;
