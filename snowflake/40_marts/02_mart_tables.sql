/* =============================================================================
   40_marts / 02  Mart tables (structure only)
   Tables are (re)created empty from the INTEGRATION.V_MART_* views and filled by
   CALL MARTS.SP_REFRESH(). Row access policies are detached first because the tables
   are replaced; run 70_security_sharing again after this script (run_pipeline.py does).
   Run as: FIN_ENGINEER
   ============================================================================= */
