/* =============================================================================
   40_marts / 03  Refresh procedure
   Materialises the INTEGRATION working tables and all MARTS tables in dependency order.
   INSERT OVERWRITE keeps grants and row access policies on the target tables.
   Called by run_pipeline.py (step "refresh") and by the task DAG (60_tasks).
   Run as: FIN_ENGINEER
   ============================================================================= */
USE ROLE FIN_ENGINEER;
USE WAREHOUSE WH_FIN_XS;
USE DATABASE HELIX_FIN;
USE SCHEMA MARTS;

CREATE OR REPLACE PROCEDURE MARTS.SP_REFRESH()
    RETURNS VARCHAR
    LANGUAGE SQL
    EXECUTE AS CALLER
    COMMENT = 'Rebuild INTEGRATION working tables and MARTS from the current STAGING data'
AS
$$
DECLARE
    started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
    fact_rows INTEGER DEFAULT 0;
BEGIN
    -- 1. INTEGRATION working tables (order matters: each one feeds the next)
    INSERT OVERWRITE INTO INTEGRATION.FX_RATES_FILLED SELECT * FROM INTEGRATION.V_FX_RATES_FILLED;
    INSERT OVERWRITE INTO INTEGRATION.GL_BS_BALANCES  SELECT * FROM INTEGRATION.V_GL_BS_BALANCES;
    INSERT OVERWRITE INTO INTEGRATION.GL_TRANSLATED   SELECT * FROM INTEGRATION.V_GL_TRANSLATED;
    INSERT OVERWRITE INTO INTEGRATION.IC_RECON        SELECT * FROM INTEGRATION.V_IC_RECON;

    -- 2. MARTS

    INSERT OVERWRITE INTO MARTS.DIM_ENTITY SELECT * FROM INTEGRATION.V_MART_DIM_ENTITY;
    INSERT OVERWRITE INTO MARTS.DIM_PARTNER SELECT * FROM INTEGRATION.V_MART_DIM_PARTNER;
    INSERT OVERWRITE INTO MARTS.DIM_ACCOUNT SELECT * FROM INTEGRATION.V_MART_DIM_ACCOUNT;
    INSERT OVERWRITE INTO MARTS.DIM_PERIOD SELECT * FROM INTEGRATION.V_MART_DIM_PERIOD;
    INSERT OVERWRITE INTO MARTS.DIM_COST_CENTER SELECT * FROM INTEGRATION.V_MART_DIM_COST_CENTER;
    INSERT OVERWRITE INTO MARTS.DIM_PROFIT_CENTER SELECT * FROM INTEGRATION.V_MART_DIM_PROFIT_CENTER;
    INSERT OVERWRITE INTO MARTS.DIM_BUSINESS_UNIT SELECT * FROM INTEGRATION.V_MART_DIM_BUSINESS_UNIT;
    INSERT OVERWRITE INTO MARTS.DIM_CURRENCY SELECT * FROM INTEGRATION.V_MART_DIM_CURRENCY;
    INSERT OVERWRITE INTO MARTS.DIM_LAYER SELECT * FROM INTEGRATION.V_MART_DIM_LAYER;
    INSERT OVERWRITE INTO MARTS.DIM_SCENARIO SELECT * FROM INTEGRATION.V_MART_DIM_SCENARIO;
    INSERT OVERWRITE INTO MARTS.FCT_CONSOLIDATED_GL SELECT * FROM INTEGRATION.V_MART_FCT_CONSOLIDATED_GL;
    INSERT OVERWRITE INTO MARTS.FCT_CASHFLOW SELECT * FROM INTEGRATION.V_MART_FCT_CASHFLOW;
    INSERT OVERWRITE INTO MARTS.FCT_IC_RECON SELECT * FROM INTEGRATION.V_MART_FCT_IC_RECON;
    INSERT OVERWRITE INTO MARTS.FCT_FX_RATE SELECT * FROM INTEGRATION.V_MART_FCT_FX_RATE;
    INSERT OVERWRITE INTO MARTS.FCT_IC_DOCUMENTS SELECT * FROM INTEGRATION.V_MART_FCT_IC_DOCUMENTS;

    SELECT COUNT(*) INTO :fact_rows FROM MARTS.FCT_CONSOLIDATED_GL;
    RETURN 'MARTS refreshed: ' || fact_rows || ' fact rows in '
           || DATEDIFF(SECOND, started, CURRENT_TIMESTAMP()) || ' s';
END;
$$;
