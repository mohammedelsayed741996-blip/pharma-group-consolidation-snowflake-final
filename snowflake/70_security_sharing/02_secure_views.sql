/* =============================================================================
   70_security_sharing / 02  Secure views for the external auditor
   Statutory view only (layers TRANSLATED, IC_ELIM, CONSOL_ADJ), aggregated to
   group-account level. Secure views hide their definition from consumers.
   Run as: FIN_ENGINEER
   ============================================================================= */
USE ROLE FIN_ENGINEER;
USE WAREHOUSE WH_FIN_XS;
USE DATABASE HELIX_FIN;
USE SCHEMA MARTS;

CREATE OR REPLACE SECURE VIEW MARTS.SV_GROUP_PL
    COMMENT = 'Consolidated statutory P&L by period and group account (EUR)'
AS
SELECT
    f.PERIOD_ID, p.FISCAL_YEAR, p.FISCAL_PERIOD, a.GROUP_ACCOUNT, a.ACCOUNT_NAME, a.FS_GROUP, a.FS_LINE,
    SUM(f.AMOUNT_GC * a.PRESENTATION_SIGN) AS AMOUNT_EUR
FROM MARTS.FCT_CONSOLIDATED_GL f
JOIN MARTS.DIM_ACCOUNT a ON a.GROUP_ACCOUNT = f.GROUP_ACCOUNT
JOIN MARTS.DIM_PERIOD p  ON p.PERIOD_ID = f.PERIOD_ID
JOIN MARTS.DIM_LAYER l   ON l.LAYER = f.LAYER
WHERE f.SCENARIO = 'ACT'
  AND l.IN_STATUTORY
  AND a.STATEMENT = 'PL'
GROUP BY f.PERIOD_ID, p.FISCAL_YEAR, p.FISCAL_PERIOD, a.GROUP_ACCOUNT, a.ACCOUNT_NAME, a.FS_GROUP, a.FS_LINE;

CREATE OR REPLACE SECURE VIEW MARTS.SV_GROUP_BS
    COMMENT = 'Consolidated statutory balance sheet (cumulative balances) by period end (EUR)'
AS
WITH mv AS (
    SELECT f.GROUP_ACCOUNT, p.PERIOD_ID, p.PERIOD_SEQ, SUM(f.AMOUNT_GC) AS MOV_GC
    FROM MARTS.FCT_CONSOLIDATED_GL f
    JOIN MARTS.DIM_PERIOD p ON p.PERIOD_ID = f.PERIOD_ID
    JOIN MARTS.DIM_LAYER l  ON l.LAYER = f.LAYER
    WHERE f.SCENARIO = 'ACT' AND l.IN_STATUTORY
    GROUP BY f.GROUP_ACCOUNT, p.PERIOD_ID, p.PERIOD_SEQ
),
grid AS (
    SELECT a.GROUP_ACCOUNT, p.PERIOD_ID, p.PERIOD_SEQ
    FROM (SELECT DISTINCT GROUP_ACCOUNT FROM mv) a
    CROSS JOIN MARTS.DIM_PERIOD p
)
SELECT
    g.PERIOD_ID, a.GROUP_ACCOUNT, a.ACCOUNT_NAME, a.STATEMENT, a.FS_GROUP, a.FS_LINE,
    SUM(COALESCE(mv.MOV_GC, 0)) OVER (PARTITION BY g.GROUP_ACCOUNT ORDER BY g.PERIOD_SEQ
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) * a.PRESENTATION_SIGN AS BALANCE_EUR
FROM grid g
JOIN MARTS.DIM_ACCOUNT a ON a.GROUP_ACCOUNT = g.GROUP_ACCOUNT
LEFT JOIN mv ON mv.GROUP_ACCOUNT = g.GROUP_ACCOUNT AND mv.PERIOD_ID = g.PERIOD_ID;

CREATE OR REPLACE SECURE VIEW MARTS.SV_IC_RECON
    COMMENT = 'Intercompany reconciliation (actuals)'
AS
SELECT PERIOD_ID, PAIR_TYPE, ENTITY_A, ENTITY_B, SIDE_A_GC, SIDE_B_GC, DIFFERENCE_GC, MATCH_STATUS
FROM MARTS.FCT_IC_RECON
WHERE SCENARIO = 'ACT';
